// scripts/generate-report-glossary.mjs — copies docs/reporting-glossary.md into
// lib/report-glossary.js, the module the sundial-reports Lambda bundles (esbuild has no .md
// loader, and the assistant reads the glossary on every turn — D-092).
//
//   node scripts/generate-report-glossary.mjs
//
// Then redeploy sundial-reports. lib/report-glossary.test.js fails while the two differ.

import { readFile, writeFile } from "node:fs/promises";

export const glossarySource = () => new URL("../docs/reporting-glossary.md", import.meta.url);
export const glossaryModule = () => new URL("../lib/report-glossary.js", import.meta.url);

/** The module text for a glossary (line endings normalized, so Windows and CI agree). */
export function moduleFor(markdown) {
  const text = markdown.replace(/\r\n/g, "\n");
  return [
    "// lib/report-glossary.js — GENERATED by scripts/generate-report-glossary.mjs from",
    "// docs/reporting-glossary.md; do not edit. The report assistant's business definitions (D-092).",
    "",
    `export const GLOSSARY = ${JSON.stringify(text)};`,
    "",
  ].join("\n");
}

// Run only as a script (the test imports moduleFor without writing anything).
if (process.argv[1]?.replace(/\\/g, "/").endsWith("scripts/generate-report-glossary.mjs")) {
  const md = await readFile(glossarySource(), "utf8");
  await writeFile(glossaryModule(), moduleFor(md), "utf8");
  console.log(`wrote lib/report-glossary.js (${md.length} characters)`);
}
